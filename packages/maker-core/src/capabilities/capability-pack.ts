/**
 * Capability pack parser, serializer, and session export/import (ROADMAP 8.7).
 *
 * A `pack.yaml` bundles expert, skills, connectors, model route, pinned notes,
 * and permission defaults. It is git-trackable, offline-importable, and incorporates
 * the Phase 4.4 security scan preview.
 */

import * as yaml from 'js-yaml';
import type { SessionLaunchRecipe, SessionManifest } from '../session/session-manifest.js';

export const CAPABILITY_PACK_VERSION = 1;

export interface CapabilityPack {
  version: 1;
  name: string;
  description?: string;
  expert: string;
  skills: string[];
  connectors: string[];
  modelRoute?: string;
  pinnedNotes: string[];
  permissions?: Record<string, 'ask' | 'auto' | 'deny'>;
  tags?: string[];
}

export interface PackSecurityFinding {
  level: 'low' | 'medium' | 'high';
  message: string;
  target: string;
}

export interface PackSecurityPreview {
  verdict: 'ok' | 'review' | 'blocked';
  findings: PackSecurityFinding[];
  summary: {
    totalFindings: number;
    high: number;
    medium: number;
    low: number;
  };
  hasAutoBash: boolean;
}

export interface PackSuggestion {
  packName: string;
  expert: string;
  score: number;
  matched: string[];
  description?: string;
}

const NAME_REGEX = /^[a-zA-Z0-9_\-.]{2,64}$/;

/**
 * Parses and validates a capability pack from YAML string or plain object.
 */
export function parseCapabilityPack(input: string | Record<string, unknown>): CapabilityPack {
  let parsed: unknown;
  if (typeof input === 'string') {
    try {
      parsed = yaml.load(input);
    } catch (err) {
      throw new Error(`Failed to parse pack YAML: ${err instanceof Error ? err.message : String(err)}`);
    }
  } else {
    parsed = input;
  }

  if (!parsed || typeof parsed !== 'object') {
    throw new Error('Invalid pack: root must be a YAML mapping');
  }

  const raw = parsed as Record<string, unknown>;

  const name = typeof raw.name === 'string' ? raw.name.trim() : '';
  if (!name || !NAME_REGEX.test(name)) {
    throw new Error(`Invalid pack name "${name}": must be 2-64 characters matching ${NAME_REGEX}`);
  }

  const expert = typeof raw.expert === 'string' ? raw.expert.trim() : 'cindy';

  const skills: string[] = Array.isArray(raw.skills)
    ? raw.skills.filter((s): s is string => typeof s === 'string' && s.trim().length > 0).map((s) => s.trim())
    : [];

  const connectors: string[] = Array.isArray(raw.connectors)
    ? raw.connectors.filter((c): c is string => typeof c === 'string' && c.trim().length > 0).map((c) => c.trim())
    : [];

  const pinnedNotes: string[] = Array.isArray(raw.pinnedNotes)
    ? raw.pinnedNotes.filter((n): n is string => typeof n === 'string' && n.trim().length > 0).map((n) => n.trim())
    : [];

  const tags: string[] = Array.isArray(raw.tags)
    ? raw.tags.filter((t): t is string => typeof t === 'string' && t.trim().length > 0).map((t) => t.trim().toLowerCase())
    : [];

  let permissions: Record<string, 'ask' | 'auto' | 'deny'> | undefined;
  if (raw.permissions && typeof raw.permissions === 'object') {
    permissions = {};
    for (const [k, v] of Object.entries(raw.permissions as Record<string, unknown>)) {
      if (v === 'ask' || v === 'auto' || v === 'deny') {
        permissions[k] = v;
      }
    }
  }

  return {
    version: 1,
    name,
    description: typeof raw.description === 'string' ? raw.description.trim() : undefined,
    expert,
    skills: Array.from(new Set(skills)),
    connectors: Array.from(new Set(connectors)),
    modelRoute: typeof raw.modelRoute === 'string' && raw.modelRoute.trim() ? raw.modelRoute.trim() : undefined,
    pinnedNotes: Array.from(new Set(pinnedNotes)),
    permissions,
    tags: Array.from(new Set(tags)),
  };
}

/**
 * Serializes a capability pack into clean, formatted YAML.
 */
export function serializeCapabilityPack(pack: CapabilityPack): string {
  const obj: Record<string, unknown> = {
    version: pack.version,
    name: pack.name,
  };

  if (pack.description) {
    obj.description = pack.description;
  }

  obj.expert = pack.expert;

  if (pack.modelRoute) {
    obj.modelRoute = pack.modelRoute;
  }

  if (pack.skills.length > 0) {
    obj.skills = pack.skills;
  }

  if (pack.connectors.length > 0) {
    obj.connectors = pack.connectors;
  }

  if (pack.pinnedNotes.length > 0) {
    obj.pinnedNotes = pack.pinnedNotes;
  }

  if (pack.permissions && Object.keys(pack.permissions).length > 0) {
    obj.permissions = pack.permissions;
  }

  if (pack.tags && pack.tags.length > 0) {
    obj.tags = pack.tags;
  }

  const yamlBody = yaml.dump(obj, {
    indent: 2,
    lineWidth: 120,
    noRefs: true,
  });

  return `# Capability Pack — ${pack.name}\n# Generated by Cindy (AGENTS.md §6: local-first, file-backed, human-editable)\n\n${yamlBody}`;
}

/**
 * Exports a session's live manifest into a reusable CapabilityPack.
 */
export function exportSessionToPack(
  manifest: SessionManifest,
  meta: { name?: string; description?: string } = {},
): CapabilityPack {
  const expertCap = manifest.capabilities.find((c) => c.kind === 'expert');
  const expert = expertCap?.id || 'cindy';

  const skills: string[] = manifest.capabilities
    .filter((c) => c.kind === 'skill' && c.enabled)
    .map((c) => c.id);

  const connectors: string[] = manifest.capabilities
    .filter((c) => c.kind === 'connector' && c.enabled)
    .map((c) => c.id);

  const pinnedNotes: string[] = manifest.capabilities
    .filter((c) => c.kind === 'pinned-note' && c.enabled)
    .map((c) => c.value);

  const modelRouteCap = manifest.capabilities.find((c) => c.kind === 'model-route');
  const modelRoute = modelRouteCap?.value || manifest.session.model || undefined;

  const permissions: Record<string, 'ask' | 'auto' | 'deny'> = {};
  const permCaps = manifest.capabilities.filter((c) => c.kind === 'permission');
  for (const p of permCaps) {
    if (p.value === 'ask' || p.value === 'auto' || p.value === 'deny') {
      permissions[p.id] = p.value;
    }
  }

  const name = meta.name?.trim() || `${expert}-pack-${manifest.session.id.slice(0, 8)}`;

  return {
    version: 1,
    name,
    description: meta.description?.trim() || `Exported capability pack from session ${manifest.session.id}`,
    expert,
    skills: Array.from(new Set(skills)),
    connectors: Array.from(new Set(connectors)),
    modelRoute,
    pinnedNotes: Array.from(new Set(pinnedNotes)),
    permissions: Object.keys(permissions).length > 0 ? permissions : undefined,
    tags: [expert],
  };
}

/**
 * Converts a CapabilityPack into a SessionLaunchRecipe for offline import into new tasks.
 */
export function importPackToLaunchRecipe(pack: CapabilityPack): SessionLaunchRecipe & { expert?: string } {
  return {
    expertSlug: pack.expert || null,
    expert: pack.expert,
    agentKind: 'hermes',
    model: pack.modelRoute || 'hermes-default',
    permissionMode: pack.permissions?.bash === 'auto' ? 'bypass' : 'normal',
    pinnedNotes: [...pack.pinnedNotes],
    skills: [...pack.skills],
    tools: [],
    connectors: [...pack.connectors],
    capabilityIds: [
      `expert:${pack.expert}`,
      ...pack.skills.map((s) => `skill:${s}`),
      ...pack.connectors.map((c) => `connector:${c}`),
      ...pack.pinnedNotes.map((n) => `pinned-note:${n}`),
    ],
  };
}

/**
 * 4.4 Security scan preview for an imported capability pack.
 * Evaluates permissions and external tooling risk prior to import.
 */
export function previewPackSecurity(
  pack: CapabilityPack,
  knownSkillFindings?: Record<string, { level: 'low' | 'medium' | 'high'; message: string }[]>,
): PackSecurityPreview {
  const findings: PackSecurityFinding[] = [];
  let hasAutoBash = false;

  // 1. Permission checks
  if (pack.permissions) {
    if (pack.permissions.bash === 'auto') {
      hasAutoBash = true;
      findings.push({
        level: 'high',
        message: 'Pack grants automatic unrestrained bash execution without user prompt.',
        target: 'permissions.bash',
      });
    }
    if (pack.permissions.write_file === 'auto') {
      findings.push({
        level: 'medium',
        message: 'Pack grants automatic write access to local files.',
        target: 'permissions.write_file',
      });
    }
  }

  // 2. Skill checks (Phase 4.4 integration)
  if (knownSkillFindings) {
    for (const skill of pack.skills) {
      const skillFindings = knownSkillFindings[skill];
      if (skillFindings && skillFindings.length > 0) {
        for (const sf of skillFindings) {
          findings.push({
            level: sf.level,
            message: sf.message,
            target: `skill:${skill}`,
          });
        }
      }
    }
  }

  // 3. Connectors checks
  for (const connector of pack.connectors) {
    if (connector.includes('eval') || connector.includes('exec') || connector.includes('sudo')) {
      findings.push({
        level: 'high',
        message: `Connector "${connector}" exhibits elevated privilege keywords.`,
        target: `connector:${connector}`,
      });
    }
  }

  const high = findings.filter((f) => f.level === 'high').length;
  const medium = findings.filter((f) => f.level === 'medium').length;
  const low = findings.filter((f) => f.level === 'low').length;

  let verdict: 'ok' | 'review' | 'blocked' = 'ok';
  if (high > 0) {
    verdict = 'blocked';
  } else if (medium > 0) {
    verdict = 'review';
  }

  return {
    verdict,
    findings,
    summary: {
      totalFindings: findings.length,
      high,
      medium,
      low,
    },
    hasAutoBash,
  };
}

/**
 * Extends 7.2 Intent Suggester from individual experts to whole capability packs.
 */
export function suggestCapabilityPack(
  prompt: string,
  packs: CapabilityPack[],
  options: { excludePack?: string; minScore?: number } = {},
): PackSuggestion | null {
  const minScore = options.minScore ?? 2;
  const normalized = prompt.toLowerCase();

  let bestSuggestion: PackSuggestion | null = null;
  let highestScore = 0;

  for (const pack of packs) {
    if (options.excludePack && pack.name === options.excludePack) {
      continue;
    }

    let score = 0;
    const matched: string[] = [];

    // Tag matching (2 pts)
    if (pack.tags) {
      for (const tag of pack.tags) {
        if (normalized.includes(tag)) {
          score += 2;
          matched.push(`tag:${tag}`);
        }
      }
    }

    // Name / Expert slug matching (3 pts)
    if (normalized.includes(pack.expert)) {
      score += 3;
      matched.push(`expert:${pack.expert}`);
    }

    // Skills matching (1 pt each)
    for (const skill of pack.skills) {
      if (normalized.includes(skill)) {
        score += 1;
        matched.push(`skill:${skill}`);
      }
    }

    // Description matching
    if (pack.description) {
      const words = pack.description.toLowerCase().split(/\s+/);
      for (const w of words) {
        if (w.length > 4 && normalized.includes(w)) {
          score += 1;
          matched.push(`keyword:${w}`);
          break;
        }
      }
    }

    if (score >= minScore && score > highestScore) {
      highestScore = score;
      bestSuggestion = {
        packName: pack.name,
        expert: pack.expert,
        score,
        matched: Array.from(new Set(matched)),
        description: pack.description,
      };
    }
  }

  return bestSuggestion;
}
