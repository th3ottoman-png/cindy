/**
 * Python flavour of the Hermes `auto` hook (ROADMAP 1.13e).
 *
 * The 1.13b hook is `node <hermes-mgr.mjs> --auto-review-hook`, which needs a
 * `node` on the Hermes gateway's PATH. A packaged Cindy has the RunAsNode fuse
 * off and ships no node, so on a machine without one every `auto` call is
 * blocked. Hermes is itself a Python program, so its own interpreter is always
 * there: the daemon finds it from the `hermes` entry script's shebang, writes
 * the small stdlib-only script below next to the registry, and points the hook
 * at `<python> -I <script> --credentials <file>`. When no interpreter can be
 * found the bin falls back to the node hook, so nothing regresses.
 *
 * The script speaks exactly what runAutoReviewHook speaks: one JSON line
 * `{token, payload}` to the unix socket, one JSON line back, `{}` + exit 0 for
 * allow, a block directive + exit 2 for anything else (fail closed).
 */

import * as fs from 'node:fs/promises';
import * as nodePath from 'node:path';

import {
  AUTO_REVIEW_CREDENTIALS_FLAG,
  AUTO_REVIEW_HOOK_FLAG,
  AUTO_REVIEW_HOOK_SOCKET_TIMEOUT_MS,
  AUTO_REVIEW_SOCKET_ENV,
  AUTO_REVIEW_TOKEN_ENV,
} from './auto-review-gate.js';

export const AUTO_REVIEW_HOOK_SCRIPT_FILE = 'auto-review-hook.py';

/** Python 3.8+, stdlib only. Keep in step with runAutoReviewHook (auto-review-gate.ts). */
export const AUTO_REVIEW_HOOK_PYTHON_SOURCE = `#!/usr/bin/env python3
# Cindy auto-review hook for Hermes (generated by hermes-mgr; do not edit).
import json
import os
import socket
import sys

CREDENTIALS_FLAG = ${JSON.stringify(AUTO_REVIEW_CREDENTIALS_FLAG)}
SOCKET_ENV = ${JSON.stringify(AUTO_REVIEW_SOCKET_ENV)}
TOKEN_ENV = ${JSON.stringify(AUTO_REVIEW_TOKEN_ENV)}
TIMEOUT_SECONDS = ${AUTO_REVIEW_HOOK_SOCKET_TIMEOUT_MS / 1000}
MAX_ANSWER_BYTES = 1 << 20


def block(reason):
    sys.stdout.write(json.dumps({"decision": "block", "reason": reason}))
    sys.stdout.flush()
    sys.exit(2)


def credentials_file():
    argv = sys.argv[1:]
    if CREDENTIALS_FLAG in argv:
        i = argv.index(CREDENTIALS_FLAG)
        if i + 1 < len(argv):
            return argv[i + 1]
    return None


def load_credentials():
    sock_path = os.environ.get(SOCKET_ENV)
    token = os.environ.get(TOKEN_ENV)
    path = credentials_file()
    if path:
        try:
            with open(path, "r", encoding="utf-8") as fh:
                creds = json.load(fh)
            if isinstance(creds.get("socketPath"), str) and isinstance(creds.get("token"), str):
                sock_path, token = creds["socketPath"], creds["token"]
        except Exception:
            pass
    return sock_path, token


def ask(sock_path, token, payload):
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.settimeout(TIMEOUT_SECONDS)
    try:
        s.connect(sock_path)
        s.sendall((json.dumps({"token": token, "payload": payload}) + "\\n").encode("utf-8"))
        buf = b""
        while b"\\n" not in buf:
            chunk = s.recv(65536)
            if not chunk:
                return None, "Cindy auto-review closed without an answer."
            buf += chunk
            if len(buf) > MAX_ANSWER_BYTES:
                return None, "Cindy auto-review sent an unreadable answer."
        line = buf.split(b"\\n", 1)[0].decode("utf-8")
        return json.loads(line), None
    except socket.timeout:
        return None, "Cindy auto-review timed out."
    except (ValueError, UnicodeError):
        return None, "Cindy auto-review sent an unreadable answer."
    except OSError:
        return None, "Cindy auto-review is unreachable."
    finally:
        try:
            s.close()
        except Exception:
            pass


def main():
    sock_path, token = load_credentials()
    if not sock_path or not token:
        block("Cindy auto-review is not connected to this Hermes run.")
    try:
        payload = json.loads(sys.stdin.read())
    except Exception:
        block("Cindy auto-review could not read the tool call.")
    answer, problem = ask(sock_path, token, payload)
    if problem:
        block(problem)
    decision = answer.get("decision") if isinstance(answer, dict) else None
    if decision == "allow":
        sys.stdout.write("{}")
        sys.stdout.flush()
        sys.exit(0)
    reason = answer.get("reason") if isinstance(answer, dict) else None
    if isinstance(reason, str) and reason.strip():
        block(reason.strip()[:2000])
    block("Cindy auto-review returned no valid decision." if decision != "block" else "Blocked by Cindy auto-review.")


try:
    main()
except SystemExit:
    raise
except BaseException:
    block("Cindy auto-review hook failed.")
`;

export interface InterpreterProbeIo {
  readHead(file: string): Promise<string>;
  /** Absolute path of an executable named `name` on PATH, else undefined. */
  which(name: string): Promise<string | undefined>;
}

const MAX_WRAPPER_HOPS = 3;

/** `#!/path/python3.14` -> ['/path/python3.14']; `#!/usr/bin/env python3` -> ['/usr/bin/env', 'python3']. */
export function parsePythonShebang(firstLine: string): string[] | undefined {
  if (!firstLine.startsWith('#!')) return undefined;
  const words = firstLine.slice(2).trim().split(/\s+/).filter(Boolean);
  if (words.length === 0 || !nodePath.isAbsolute(words[0]!)) return undefined;
  const base = nodePath.basename(words[0]!);
  const target = base === 'env' ? words[1] : base;
  if (!target || !/^python[0-9.]*$/.test(nodePath.basename(target))) return undefined;
  return words;
}

/** The `exec <absolute path> "$@"` target of a small `sh` wrapper script, if that is what it is. */
export function parseShellExecTarget(head: string): string | undefined {
  const lines = head.split('\n');
  if (!/^#!\s*\/\S*\b(?:ba|z|da)?sh\b/.test(lines[0] ?? '')) return undefined;
  for (const line of lines.slice(1)) {
    const m = /^\s*exec\s+(?:"([^"]+)"|'([^']+)'|(\S+))/.exec(line);
    const target = m?.[1] ?? m?.[2] ?? m?.[3];
    if (target && nodePath.isAbsolute(target)) return target;
  }
  return undefined;
}

/**
 * The interpreter argv Hermes itself runs under, read from the shebang of the
 * `hermes` entry script (following small `sh` wrappers, or the Python an `sh`
 * wrapper execs directly). Undefined when it
 * cannot be told, which sends the caller to the node hook.
 */
export async function resolveHermesInterpreter(
  hermesBin: string,
  io: InterpreterProbeIo,
): Promise<string[] | undefined> {
  let file: string | undefined = nodePath.isAbsolute(hermesBin) ? hermesBin : await io.which(hermesBin);
  for (let hop = 0; file && hop <= MAX_WRAPPER_HOPS; hop++) {
    let head: string;
    try {
      head = await io.readHead(file);
    } catch {
      return undefined;
    }
    const shebang = parsePythonShebang(head.split('\n')[0] ?? '');
    if (shebang) return shebang;
    const target = parseShellExecTarget(head);
    // Hermes 0.22.7's entry script is an sh wrapper that execs its Python directly.
    if (target && /^python[0-9.]*$/.test(nodePath.basename(target))) return [target];
    file = target;
  }
  return undefined;
}

export async function writeHookScript(file: string): Promise<void> {
  await fs.mkdir(nodePath.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  await fs.writeFile(tmp, AUTO_REVIEW_HOOK_PYTHON_SOURCE, { mode: 0o700 });
  await fs.rename(tmp, file);
}

export interface PrepareHookArgvOptions {
  hermesBin: string;
  /** Directory the script is written to (the daemon's own state dir). */
  stateDir: string;
  /** This daemon bundle, for the node fallback. */
  bundlePath: string;
  io: InterpreterProbeIo;
  log?: (message: string, ctx?: Record<string, unknown>) => void;
}

/** Python hook when Hermes's interpreter is known, otherwise `node <bundle> --auto-review-hook`. */
export async function prepareAutoReviewHookArgv(opts: PrepareHookArgvOptions): Promise<string[]> {
  const nodeFallback = ['node', opts.bundlePath, AUTO_REVIEW_HOOK_FLAG];
  try {
    const interpreter = await resolveHermesInterpreter(opts.hermesBin, opts.io);
    if (!interpreter) {
      opts.log?.('auto-review hook: no Hermes interpreter found, using node', {});
      return nodeFallback;
    }
    const script = nodePath.join(opts.stateDir, AUTO_REVIEW_HOOK_SCRIPT_FILE);
    await writeHookScript(script);
    return [...interpreter, '-I', script];
  } catch (error) {
    opts.log?.('auto-review hook: python hook setup failed, using node', {
      error: error instanceof Error ? error.message : String(error),
    });
    return nodeFallback;
  }
}
